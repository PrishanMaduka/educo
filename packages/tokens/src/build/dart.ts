import { colorNames, colors, type ColorSet } from '../colors';
import { heatHex, publicSite } from '../public-site';
import { radius, shadow, spacing } from '../shape';
import { fontName } from '../type';

const HEADER = '// GENERATED by pnpm tokens:build — do not edit\n';

const camel = (name: string): string =>
  name.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());

const publicNames = Object.keys(publicSite.light) as (keyof typeof publicSite.light)[];
const heatNames = publicSite.heat.map((_, i) => `heat-${i}`);
const allNames: string[] = [...colorNames, ...publicNames, ...heatNames];

/** Every colour of one theme (core, public site and heat), keyed by token name. */
function themeValues(theme: 'light' | 'dark'): Record<string, string> {
  const out: Record<string, string> = { ...colors[theme], ...publicSite[theme] };
  publicSite.heat.forEach((_, i) => {
    out[`heat-${i}`] = heatHex(colors[theme], i);
  });
  return out;
}

const color = (hex: string): string => `Color(0xFF${hex.slice(1).toUpperCase()})`;

function instance(name: string, values: Record<string, string>): string {
  const fields = allNames.map((n) => `    ${camel(n)}: ${color(values[n] ?? '')},`);
  return `  static const ${name} = QuadColors(\n${fields.join('\n')}\n  );\n`;
}

/** Parses "0 8px 24px -12px rgba(28,27,46,.18)" into a const BoxShadow. */
function boxShadow(css: string): string {
  const m = /^(-?\d+)(?:px)? (-?\d+)(?:px)? (\d+)px(?: (-?\d+)px)? rgba\((\d+),(\d+),(\d+),([\d.]+)\)$/.exec(
    css.trim(),
  );
  if (!m) throw new Error(`Unsupported shadow: ${css}`);
  const [, dx = '0', dy = '0', blur = '0', spread = '0', r = '0', g = '0', b = '0', a = '1'] = m;
  const alpha = Math.round(Number(a) * 255)
    .toString(16)
    .padStart(2, '0')
    .toUpperCase();
  const hex = [r, g, b].map((v) => Number(v).toString(16).padStart(2, '0')).join('').toUpperCase();
  const parts = [
    `color: Color(0x${alpha}${hex})`,
    `blurRadius: ${blur}`,
    ...(Number(spread) === 0 ? [] : [`spreadRadius: ${spread}`]),
    `offset: Offset(${dx}, ${dy})`,
  ];
  const oneLine = `    BoxShadow(${parts.join(', ')}),`;
  if (oneLine.length <= 80) return oneLine;
  // dart format breaks one argument per line when the call does not fit in 80 columns.
  return `    BoxShadow(\n${parts.map((x) => `      ${x},`).join('\n')}\n    ),`;
}

function shadowList(css: string): string {
  const layers = css.split(/(?<=\)),\s*/).map(boxShadow);
  return `[\n${layers.join('\n')}\n  ]`;
}

function tokensClass(): string {
  const radii = Object.entries(radius).map(
    ([n, v]) => `  static const double radius${n[0]?.toUpperCase()}${n.slice(1)} = ${v};`,
  );
  return [
    '/// Shape, space, elevation and font names. Colours live in [QuadColors].',
    'class QuadTokens {',
    '  const QuadTokens._();',
    '',
    ...radii,
    '',
    '  static const List<double> spacing = [',
    ...spacing.map((v) => `    ${v},`),
    '  ];',
    '',
    `  static const List<BoxShadow> shadowCard = ${shadowList(shadow.card)};`,
    `  static const List<BoxShadow> shadowLg = ${shadowList(shadow.lg)};`,
    '',
    `  static const String fontSans = '${fontName.sans}';`,
    `  static const String fontAccent = '${fontName.accent}';`,
    '}',
    '',
  ].join('\n');
}

function colorsClass(): string {
  const fields = allNames.map(camel);
  const consoleOver = (rail: ColorSet['rail'], rail2: string, active: string, theme: 'light' | 'dark') => ({
    ...themeValues(theme),
    rail,
    'rail-2': rail2,
    'rail-active': active,
  });
  const cl = colors.console;
  const cd = colors.consoleDark;
  return [
    '/// Every colour of the Quad design system, one instance per theme.',
    '/// Read it with `Theme.of(context).extension<QuadColors>()!`.',
    '@immutable',
    'class QuadColors extends ThemeExtension<QuadColors> {',
    '  const QuadColors({',
    ...fields.map((f) => `    required this.${f},`),
    '  });',
    '',
    ...fields.map((f) => `  final Color ${f};`),
    '',
    instance('light', themeValues('light')),
    instance('dark', themeValues('dark')),
    '  /// Console overrides: the console has its own, darker rail.',
    instance('consoleLight', consoleOver(cl.rail, cl['rail-2'], cl['rail-active'], 'light')),
    instance('consoleDark', consoleOver(cd.rail, cd['rail-2'], cd['rail-active'], 'dark')),
    '  @override',
    '  QuadColors copyWith({',
    ...fields.map((f) => `    Color? ${f},`),
    '  }) {',
    '    return QuadColors(',
    ...fields.map((f) => `      ${f}: ${f} ?? this.${f},`),
    '    );',
    '  }',
    '',
    '  @override',
    '  QuadColors lerp(ThemeExtension<QuadColors>? other, double t) {',
    '    if (other is! QuadColors) return this;',
    '    return QuadColors(',
    ...fields.map((f) => `      ${f}: Color.lerp(${f}, other.${f}, t)!,`),
    '    );',
    '  }',
    '}',
    '',
  ].join('\n');
}

export function buildDart(): string {
  return [
    HEADER,
    "import 'package:flutter/material.dart';",
    '',
    tokensClass(),
    colorsClass(),
  ].join('\n');
}
